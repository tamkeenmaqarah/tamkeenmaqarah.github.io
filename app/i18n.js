let language = "en";
const listeners = new Set();
export const getLanguage = () => language;
export function subscribeLanguage(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}
function applyLanguage() {
  if (typeof document === "undefined") return;
  document.documentElement.lang = language;
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
  document.title =
    language === "ar"
      ? "أصحاب الخيمة | لوحة المعلّم"
      : "Ashab Al Khaimah · Teacher dashboard";
}
export function setLanguage(next) {
  if (!["en", "ar"].includes(next) || next === language) return;
  language = next;
  try {
    localStorage.setItem("tamkeen-language", language);
  } catch {
    /* Preference lasts for this visit. */
  }
  applyLanguage();
  listeners.forEach((listener) => listener());
}
export function t(message, values = {}) {
  const text = language === "ar" ? (arabic[message] ?? (arabic[message.trim()] ? message.replace(message.trim(),arabic[message.trim()]) : message)) : message;
  return text.replace(/\{(\w+)\}/g, (match, key) =>
    Object.hasOwn(values, key) ? String(values[key]) : match,
  );
}
