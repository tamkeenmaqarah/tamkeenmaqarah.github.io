import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import fs from 'node:fs';
import ts from 'typescript';
import vm from 'node:vm';
const require=createRequire(import.meta.url);
const exports={};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('app/revisit.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{exports,require});
const {spellName,missesFrom,gradePractice}=exports;
assert.equal(spellName('  yaseen ',['Yaseen','Hassonah']),'Yaseen');
assert.equal(spellName('Yasin',['Yaseen']),'Yasin');
const questions=[{prompt:'Which tree is used for siwak?',options:['ar-Ruman','al-Arak','al-Zaytun','al-Tin'],explanation:'The siwak tree is al-Arak.'}];
const review=[{correct:'al-Arak',explanation:'The siwak tree is al-Arak.',right:false}];
const misses=missesFrom(questions,review);
assert.equal(misses.length,1);
assert.equal(misses[0].correct,1);
const again=gradePractice(misses,[1]);
assert.equal(again.score,1);
assert.equal(again.misses.length,0);
const still=gradePractice(misses,[0]);
assert.equal(still.score,0);
assert.equal(still.misses.length,1);
assert.equal(missesFrom(questions,[{correct:'al-Arak',right:true}]).length,0);
console.log('PASS: name spelling, missed questions, and private practice stay off the leaderboard.');
